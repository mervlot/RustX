func TestFunctionObject(t *testing.T) {
	input := "func(x int) int { x + 2; };"

	evaluated := testEval(input)
	fn, ok := evaluated.(*object.Function)
	if !ok {
		t.Fatalf("object is not Function. got=%T (%+v)", evaluated, evaluated)
	}

	if len(fn.Parameters) != 1 {
		t.Fatalf("function has wrong parameters. Parameters=%+v", fn.Parameters)
	}

	if fn.Parameters[0].Name.Value != "x" {
		t.Fatalf("parameter name is not 'x'. got=%q", fn.Parameters[0].Name.Value)
	}

	expectedBody := "(x + 2)"

	if fn.Body.String() != expectedBody {
		t.Fatalf("body is not %q. got=%q", expectedBody, fn.Body.String())
	}
}

func TestFunctionApplication(t *testing.T) {
	tests := []struct {
		input    string
		expected int64
	}{
		{"var identity = func(x int) int { x; }; identity(5);", 5},
		{"var identity = func(x int) int { return x; }; identity(5);", 5},
		{"var double = func(x int) int { x * 2; }; double(5);", 10},
		{"var add = func(x int, y int) int { x + y; }; add(5, 5);", 10},
		{"var add = func(x int, y int) int { x + y; }; add(5 + 5, add(5, 5));", 20},
		{"func sum(a int, b int) int { return a + b; }; sum(3, 4);", 7},
	}

	for _, tt := range tests {
		testIntegerObject(t, testEval(tt.input), tt.expected)
	}
}


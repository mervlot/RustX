func TestVarStatements(t *testing.T) {
	input := `
var x = 5;
y := 10;
var foobar = 15.5;
`
	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 3 {
		t.Fatalf("program.Statements does not contain 3 statements. got=%d", len(program.Statements))
	}

	tests := []struct {
		expectedIdentifier string
	}{
		{"x"},
		{"y"},
		{"foobar"},
	}

	for i, tt := range tests {
		stmt := program.Statements[i]
		if !testVarStatement(t, stmt, tt.expectedIdentifier) {
			return
		}
	}
}

func testVarStatement(t *testing.T, s ast.Statement, name string) bool {
	varStatement, ok := s.(*ast.VarStatement)
	if !ok {
		// Sometime shorthand is parsed as VarStatement
		exprStmt, ok := s.(*ast.ExpressionStatement)
		if ok {
			varStatement, ok = exprStmt.Expression.(*ast.VarStatement)
		}
		if !ok {
			t.Errorf("s not *ast.VarStatement. got=%T", s)
			return false
		}
	}

	if varStatement.Name.Value != name {
		t.Errorf("varStatement.Name.Value not '%s'. got='%s'", name, varStatement.Name.Value)
		return false
	}

	if varStatement.Name.TokenLiteral() != name {
		t.Errorf("varStatement.Name.TokenLiteral() not '%s'. got='%s'", name, varStatement.Name.TokenLiteral())
		return false
	}

	return true
}


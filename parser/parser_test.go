func TestForExpressions(t *testing.T) {
	input := `
	for i := 0; i < 10; i++ {
		println(i)
	}
	`

	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 1 {
		t.Fatalf("program.Statements does not contain 1 statements. got=%d", len(program.Statements))
	}

	stmt, ok := program.Statements[0].(*ast.ExpressionStatement)
	if !ok {
		t.Fatalf("program.Statements[0] is not ast.ExpressionStatement. got=%T", program.Statements[0])
	}

	forExp, ok := stmt.Expression.(*ast.ForExpression)
	if !ok {
		t.Fatalf("stmt.Expression is not *ast.ForExpression. got=%T", stmt.Expression)
	}

	// Init
	if forExp.Init == nil {
		t.Fatalf("forExp.Init is nil")
	}
	sas, ok := forExp.Init.(*ast.ShorthandAssignStatement)
	if !ok {
		t.Fatalf("forExp.Init is not *ast.ShorthandAssignStatement. got=%T", forExp.Init)
	}
	if sas.Name.Value != "i" {
		t.Errorf("sas.Name.Value not 'i'. got=%q", sas.Name.Value)
	}

	// Condition
	if forExp.Condition == nil {
		t.Fatalf("forExp.Condition is nil")
	}

	// Post
	if forExp.Post == nil {
		t.Fatalf("forExp.Post is nil")
	}
}

func checkParserErrors(t *testing.T, p *Parser) {
	errors := p.Errors()
	if len(errors) == 0 {
		return
	}

	t.Errorf("parser has %d errors", len(errors))
	for _, err := range errors {
		t.Errorf("parser error: %s", err)
	}
	t.FailNow()
}

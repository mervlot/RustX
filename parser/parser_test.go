func TestFunctionLiteralParsing(t *testing.T) {
	input := "func add(x int, y int) int { return x + y; }"

	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 1 {
		t.Fatalf("program.Statements does not contain 1 statement. got=%d", len(program.Statements))
	}

	stmt, ok := program.Statements[0].(*ast.ExpressionStatement)
	if !ok {
		t.Fatalf("program.Statements[0] is not ast.ExpressionStatement. got=%T", program.Statements[0])
	}

	function, ok := stmt.Expression.(*ast.FunctionLiteral)
	if !ok {
		t.Fatalf("stmt.Expression is not ast.FunctionLiteral. got=%T", stmt.Expression)
	}

	if function.Name != "add" {
		t.Errorf("function.Name is not 'add'. got='%s'", function.Name)
	}

	if len(function.Parameters) != 2 {
		t.Fatalf("function parameters wrong. want 2, got=%d", len(function.Parameters))
	}

	if function.Parameters[0].Value != "x" {
		t.Errorf("parameter 0 is not 'x'. got=%q", function.Parameters[0].Value)
	}

	if function.Parameters[1].Value != "y" {
		t.Errorf("parameter 1 is not 'y'. got=%q", function.Parameters[1].Value)
	}

	if function.ReturnType != "int" {
		t.Errorf("function return type is not 'int'. got=%q", function.ReturnType)
	}
}

func checkParserErrors(t *testing.T, p *Parser) {
	errors := p.Errors()
	if len(errors) == 0 {
		return
	}

	t.Errorf("parser has %d errors", len(errors))
	for _, err := range errors {
		t.Errorf("parser error: %q", err.Error())
	}
	t.FailNow()
}

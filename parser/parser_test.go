func TestVarStatements(t *testing.T) {
	input := `
var x = 5;
var y int = 10;
var foobar = true;
`
	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 3 {
		t.Fatalf("program.Statements does not contain 3 statements. got=%d", len(program.Statements))
	}

	tests := []struct {
		expectedIdentifier string
		expectedType       string
	}{
		{"x", ""},
		{"y", "int"},
		{"foobar", ""},
	}

	for i, tt := range tests {
		stmt := program.Statements[i]
		if !testVarStatement(t, stmt, tt.expectedIdentifier, tt.expectedType) {
			return
		}
	}
}

func testVarStatement(t *testing.T, s ast.Statement, name string, typeAnn string) bool {
	if s.TokenLiteral() != "var" {
		t.Errorf("s.TokenLiteral not 'var'. got=%q", s.TokenLiteral())
		return false
	}

	varStmt, ok := s.(*ast.VarStatement)
	if !ok {
		t.Errorf("s not *ast.VarStatement. got=%T", s)
		return false
	}

	if varStmt.Name.Value != name {
		t.Errorf("varStmt.Name.Value not '%s'. got=%q", name, varStmt.Name.Value)
		return false
	}

	if varStmt.Type != typeAnn {
		t.Errorf("varStmt.Type not '%s'. got=%q", typeAnn, varStmt.Type)
		return false
	}

	return true
}

func TestShorthandAndNormalAssignment(t *testing.T) {
	input := `
x := 10;
x = 20;
`
	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 2 {
		t.Fatalf("expected 2 statements, got %d", len(program.Statements))
	}

	// First statement: ShorthandAssignStatement
	shorthand, ok := program.Statements[0].(*ast.ShorthandAssignStatement)
	if !ok {
		t.Fatalf("expected *ast.ShorthandAssignStatement, got=%T", program.Statements[0])
	}
	if shorthand.Name.Value != "x" {
		t.Errorf("expected shorthand name to be 'x', got=%q", shorthand.Name.Value)
	}

	// Second statement: AssignStatement
	assign, ok := program.Statements[1].(*ast.AssignStatement)
	if !ok {
		t.Fatalf("expected *ast.AssignStatement, got=%T", program.Statements[1])
	}
	ident, ok := assign.Name.(*ast.Identifier)
	if !ok {
		t.Fatalf("expected assignment target to be *ast.Identifier, got=%T", assign.Name)
	}
	if ident.Value != "x" {
		t.Errorf("expected assignment target to be 'x', got=%q", ident.Value)
	}
}


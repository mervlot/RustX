func TestIfExpression(t *testing.T) {
	input := "if x < y { x } else { y }"

	l := lexer.New(input)
	p := New(l)
	program := p.ParseProgram()
	checkParserErrors(t, p)

	if len(program.Statements) != 1 {
		t.Fatalf("program.Statements does not contain 1 statement. got=%d", len(program.Statements))
	}

	stmt, ok := program.Statements[0].(*ast.ExpressionStatement)
	if !ok {
		t.Fatalf("program.Statements[0] is not *ast.ExpressionStatement. got=%T", program.Statements[0])
	}

	exp, ok := stmt.Expression.(*ast.IfExpression)
	if !ok {
		t.Fatalf("stmt.Expression is not *ast.IfExpression. got=%T", stmt.Expression)
	}

	if exp.Condition.String() != "(x < y)" {
		t.Errorf("condition is not (x < y). got=%s", exp.Condition.String())
	}

	if len(exp.Consequence.Statements) != 1 {
		t.Errorf("consequence is not 1 statement. got=%d", len(exp.Consequence.Statements))
	}

	consequence, ok := exp.Consequence.Statements[0].(*ast.ExpressionStatement)
	if !ok {
		t.Fatalf("consequence statement is not *ast.ExpressionStatement. got=%T", exp.Consequence.Statements[0])
	}

	if consequence.Expression.String() != "x" {
		t.Errorf("consequence expression is not 'x'. got=%s", consequence.Expression.String())
	}

	if exp.Alternative == nil {
		t.Fatalf("alternative is nil")
	}

	if len(exp.Alternative.Statements) != 1 {
		t.Errorf("alternative is not 1 statement. got=%d", len(exp.Alternative.Statements))
	}

	alternative, ok := exp.Alternative.Statements[0].(*ast.ExpressionStatement)
	if !ok {
		t.Fatalf("alternative statement is not *ast.ExpressionStatement. got=%T", exp.Alternative.Statements[0])
	}

	if alternative.Expression.String() != "y" {
		t.Errorf("alternative expression is not 'y'. got=%s", alternative.Expression.String())
	}
}


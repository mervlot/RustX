// Node is the base interface for all AST nodes.
type Node interface {
	TokenLiteral() string
	String() string
	GetToken() token.Token
}

// Statement interface.
type Statement interface {
	Node
	statementNode()
}

// Expression interface.
type Expression interface {
	Node
	expressionNode()
}

// Program is the root node of every AST.
type Program struct {
	Statements []Statement
}

func (p *Program) TokenLiteral() string {
	if len(p.Statements) > 0 {
		return p.Statements[0].TokenLiteral()
	}
	return ""
}

func (p *Program) GetToken() token.Token {
	if len(p.Statements) > 0 {
		return p.Statements[0].GetToken()
	}
	return token.Token{Type: token.EOF}
}

func (p *Program) String() string {
	var out bytes.Buffer
	for _, s := range p.Statements {
		out.WriteString(s.String())
	}
	return out.String()
}

// Identifier expression node.
type Identifier struct {
	Token token.Token // token.IDENT
	Value string
}

func (i *Identifier) expressionNode()      {}
func (i *Identifier) TokenLiteral() string { return i.Token.Literal }
func (i *Identifier) GetToken() token.Token { return i.Token }
func (i *Identifier) String() string       { return i.Value }

// VarStatement represents var x = value or shorthand x := value or typed var x int = value.
type VarStatement struct {
	Token token.Token // token.VAR or token.COLON_ASSIGN
	Name  *Identifier
	Type  string // optional type annotation e.g. "int"
	Value Expression
}

func (vs *VarStatement) statementNode()       {}
func (vs *VarStatement) TokenLiteral() string { return vs.Token.Literal }
func (vs *VarStatement) GetToken() token.Token { return vs.Token }
func (vs *VarStatement) String() string {
	var out bytes.Buffer
	if vs.Token.Type == token.VAR {
		out.WriteString("var ")
		out.WriteString(vs.Name.String())
		if vs.Type != "" {
			out.WriteString(" " + vs.Type)
		}
		if vs.Value != nil {
			out.WriteString(" = ")
			out.WriteString(vs.Value.String())
		}
	} else { // COLON_ASSIGN
		out.WriteString(vs.Name.String())
		out.WriteString(" := ")
		if vs.Value != nil {
			out.WriteString(vs.Value.String())
		}
	}
	out.WriteString(";")
	return out.String()
}


package ast

import (
	"bytes"
	"strings"

	"github.com/username/rustx/token"
)

type Node interface {
	TokenLiteral() string
	String() string
	GetToken() token.Token
}

type Statement interface {
	Node
	statementNode()
}

type Expression interface {
	Node
	expressionNode()
}

// Program is the root node of every AST
type Program struct {
	Statements []Statement
}

func (p *Program) TokenLiteral() string {
	if len(p.Statements) > 0 {
		return p.Statements[0].TokenLiteral()
	}
	return ""
}

func (p *Program) GetToken() token.Token {
	if len(p.Statements) > 0 {
		return p.Statements[0].GetToken()
	}
	return token.Token{}
}

func (p *Program) String() string {
	var out bytes.Buffer
	for _, s := range p.Statements {
		out.WriteString(s.String())
	}
	return out.String()
}

// Identifier represents variable/function names
type Identifier struct {
	Token token.Token // token.IDENT token
	Value string
}

func (i *Identifier) expressionNode()      {}
func (i *Identifier) TokenLiteral() string { return i.Token.Literal }
func (i *Identifier) GetToken() token.Token { return i.Token }
func (i *Identifier) String() string       { return i.Value }

// VarStatement represents 'var x = val;' or 'var x int = val;'
type VarStatement struct {
	Token token.Token // token.VAR token
	Name  *Identifier
	Type  string // optional type annotation, e.g., "int", "string"
	Value Expression
}

func (v *VarStatement) statementNode()       {}
func (v *VarStatement) TokenLiteral() string { return v.Token.Literal }
func (v *VarStatement) GetToken() token.Token { return v.Token }
func (v *VarStatement) String() string {
	var out bytes.Buffer
	out.WriteString(v.TokenLiteral() + " " + v.Name.String())
	if v.Type != "" {
		out.WriteString(" " + v.Type)
	}
	if v.Value != nil {
		out.WriteString(" = " + v.Value.String())
	}
	out.WriteString(";")
	return out.String()
}

// AssignStatement represents assignment: 'x = val' or 'x := val'
type AssignStatement struct {
	Token token.Token // token.ASSIGN or token.COLON_ASSIGN
	Name  *Identifier
	Value Expression
}

func (a *AssignStatement) statementNode()       {}
func (a *AssignStatement) expressionNode()      {}
func (a *AssignStatement) TokenLiteral() string { return a.Token.Literal }
func (a *AssignStatement) GetToken() token.Token { return a.Token }
func (a *AssignStatement) String() string {
	var out bytes.Buffer
	out.WriteString(a.Name.String() + " " + a.TokenLiteral() + " " + a.Value.String() + ";")
	return out.String()
}


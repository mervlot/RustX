// ForExpression represents `for init; condition; post { body }` or `for condition { body }`.
type ForExpression struct {
	Token     token.Token // token.FOR
	Init      Statement   // can be nil, or VarStatement / ShortVarStatement / ExpressionStatement
	Condition Expression  // can be nil
	Post      Statement   // can be nil, or ExpressionStatement / AssignStatement
	Body      *BlockStatement
}

func (fe *ForExpression) expressionNode()      {}
func (fe *ForExpression) TokenLiteral() string { return fe.Token.Literal }
func (fe *ForExpression) GetToken() token.Token { return fe.Token }
func (fe *ForExpression) String() string {
	var out bytes.Buffer
	out.WriteString("for ")
	if fe.Init != nil {
		out.WriteString(fe.Init.String() + "; ")
	}
	if fe.Condition != nil {
		out.WriteString(fe.Condition.String())
	}
	if fe.Post != nil {
		out.WriteString("; " + fe.Post.String())
	}
	out.WriteString(" " + fe.Body.String())
	return out.String()
}

// FunctionParam represents a function parameter with an optional type annotation.
type FunctionParam struct {
	Name *Identifier
	Type string // e.g., "int", "string", or empty
}

// FunctionLiteral represents `func name(a int, b int) int { ... }` or anonymous `func(x) { ... }`.
type FunctionLiteral struct {
	Token      token.Token // token.FUNCTION
	Name       string      // optional function name (empty for anonymous)
	Parameters []*FunctionParam
	ReturnType string // optional return type
	Body       *BlockStatement
}

func (fl *FunctionLiteral) expressionNode()      {}
func (fl *FunctionLiteral) TokenLiteral() string { return fl.Token.Literal }
func (fl *FunctionLiteral) GetToken() token.Token { return fl.Token }
func (fl *FunctionLiteral) String() string {
	var out bytes.Buffer
	params := make([]string, 0, len(fl.Parameters))
	for _, p := range fl.Parameters {
		if p.Type != "" {
			params = append(params, p.Name.String()+" "+p.Type)
		} else {
			params = append(params, p.Name.String())
		}
	}
	out.WriteString("func")
	if fl.Name != "" {
		out.WriteString(" " + fl.Name)
	}
	out.WriteString("(")
	out.WriteString(strings.Join(params, ", "))
	out.WriteString(")")
	if fl.ReturnType != "" {
		out.WriteString(" " + fl.ReturnType)
	}
	out.WriteString(" ")
	out.WriteString(fl.Body.String())
	return out.String()
}

// CallExpression represents `func(arg1, arg2)`.
type CallExpression struct {
	Token     token.Token // '(' token
	Function  Expression  // Identifier or FunctionLiteral
	Arguments []Expression
}

func (ce *CallExpression) expressionNode()      {}
func (ce *CallExpression) TokenLiteral() string { return ce.Token.Literal }
func (ce *CallExpression) GetToken() token.Token { return ce.Token }
func (ce *CallExpression) String() string {
	var out bytes.Buffer
	args := make([]string, 0, len(ce.Arguments))
	for _, a := range ce.Arguments {
		args = append(args, a.String())
	}
	out.WriteString(ce.Function.String())
	out.WriteString("(")
	out.WriteString(strings.Join(args, ", "))
	out.WriteString(")")
	return out.String()
}

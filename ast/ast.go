type ForExpression struct {
	Token     token.Token // token.FOR
	Init      Statement   // e.g. i := 0 or var i = 0
	Condition Expression  // e.g. i < 10
	Post      Statement   // e.g. i++
	Body      *BlockStatement
}

func (fe *ForExpression) expressionNode()      {}
func (fe *ForExpression) TokenLiteral() string { return fe.Token.Literal }
func (fe *ForExpression) GetToken() token.Token { return fe.Token }
func (fe *ForExpression) String() string {
	var out bytes.Buffer
	out.WriteString("for ")
	if fe.Init != nil {
		out.WriteString(fe.Init.String() + " ")
	}
	if fe.Condition != nil {
		out.WriteString(fe.Condition.String() + "; ")
	}
	if fe.Post != nil {
		out.WriteString(fe.Post.String() + " ")
	}
	out.WriteString(fe.Body.String())
	return out.String()
}

type Parameter struct {
	Name *Identifier
	Type string // optional type
}

type FunctionLiteral struct {
	Token      token.Token // token.FUNC
	Name       string      // optional function name (e.g. func main())
	Parameters []*Parameter
	ReturnType string          // optional return type (e.g. int)
	Body       *BlockStatement
}

func (fl *FunctionLiteral) expressionNode()      {}
func (fl *FunctionLiteral) TokenLiteral() string { return fl.Token.Literal }
func (fl *FunctionLiteral) GetToken() token.Token { return fl.Token }
func (fl *FunctionLiteral) String() string {
	var out bytes.Buffer
	params := []string{}
	for _, p := range fl.Parameters {
		pStr := p.Name.String()
		if p.Type != "" {
			pStr += " " + p.Type
		}
		params = append(params, pStr)
	}
	out.WriteString("func ")
	if fl.Name != "" {
		out.WriteString(fl.Name + " ")
	}
	out.WriteString("(" + strings.Join(params, ", ") + ") ")
	if fl.ReturnType != "" {
		out.WriteString(fl.ReturnType + " ")
	}
	out.WriteString(fl.Body.String())
	return out.String()
}

type CallExpression struct {
	Token     token.Token // '(' token
	Function  Expression  // Identifier or FunctionLiteral
	Arguments []Expression
}

func (ce *CallExpression) expressionNode()      {}
func (ce *CallExpression) TokenLiteral() string { return ce.Token.Literal }
func (ce *CallExpression) GetToken() token.Token { return ce.Token }
func (ce *CallExpression) String() string {
	var out bytes.Buffer
	args := []string{}
	for _, a := range ce.Arguments {
		args = append(args, a.String())
	}
	out.WriteString(ce.Function.String())
	out.WriteString("(" + strings.Join(args, ", ") + ")")
	return out.String()
}

type ArrayLiteral struct {
	Token    token.Token // '[' token
	Elements []Expression
}

func (al *ArrayLiteral) expressionNode()      {}
func (al *ArrayLiteral) TokenLiteral() string { return al.Token.Literal }
func (al *ArrayLiteral) GetToken() token.Token { return al.Token }
func (al *ArrayLiteral) String() string {
	var out bytes.Buffer
	elements := []string{}
	for _, el := range al.Elements {
		elements = append(elements, el.String())
	}
	out.WriteString("[" + strings.Join(elements, ", ") + "]")
	return out.String()
}

type IndexExpression struct {
	Token token.Token // '[' token
	Left  Expression  // Array expression
	Index Expression
}

func (ie *IndexExpression) expressionNode()      {}
func (ie *IndexExpression) TokenLiteral() string { return ie.Token.Literal }
func (ie *IndexExpression) GetToken() token.Token { return ie.Token }
func (ie *IndexExpression) String() string {
	return "(" + ie.Left.String() + "[" + ie.Index.String() + "])"
}
